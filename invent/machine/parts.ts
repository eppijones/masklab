/**
 * The machine's part library — the single source of truth.
 *
 * `dims` is the ONLY place a number lives. It feeds the twin (build()), the parts table,
 * the BOM, the build manual's step text, the STL export and the drawings. Change a plate
 * thickness here and all six update. That property is the reason this is code and not a
 * CAD file we'd have to retype dimensions out of.
 */

