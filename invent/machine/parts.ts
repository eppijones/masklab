export type PartKind = 'printed' | 'cots' | 'extrusion' | 'motor' | 'electronic' | 'yarn' | 'workpiece';
export type Vec3 = [number, number, number];

export interface PartDef {
  id: string;
  name: string;
  nameNo: string;
  kind: PartKind;
  /** Millimetres. The only place dimensions are written down. */
  dims: Record<string, number>;
  material?: string;
  qty: number;
  unitEur?: number;
  /** Frame this part rides on. Motion comes from the frame, never from a baked transform. */
  mount: { frame: FrameId; position: Vec3; rotation?: Vec3 };
  /** Extra copies, offset in the same frame. */
  repeats?: { position: Vec3; rotation?: Vec3 }[];
  explodeDir?: Vec3;
  group: 'frame' | 'former' | 'station' | 'head' | 'yarn' | 'control' | 'sensing' | 'workpiece';
  note: string;
  build: (d: Record<string, number>) => THREE.BufferGeometry;
}

